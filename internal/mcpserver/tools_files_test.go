func TestListGCodeFilesSorting(t *testing.T) {
	files := []moonraker.FileMetadata{
		{Filename: "a.gcode", Size: 100, Modified: 300},
		{Filename: "b.gcode", Size: 300, Modified: 100},
		{Filename: "c.gcode", Size: 200, Modified: 200},
	}
	deps, _ := singlePrinterDeps(t, domain.PresetMonitor, map[string]http.HandlerFunc{
		"/server/files/directory": directoryFixtureHandler(t, files, moonraker.DiskUsage{Total: 1000, Used: 500, Free: 500}),
	})
	cs := testSession(t, deps)

	cases := []struct {
		sortBy string
		order  []string
	}{
		{"", []string{"a.gcode", "c.gcode", "b.gcode"}}, // default: modified desc
		{"modified", []string{"a.gcode", "c.gcode", "b.gcode"}},
		{"name", []string{"a.gcode", "b.gcode", "c.gcode"}}, // asc
		{"size", []string{"b.gcode", "c.gcode", "a.gcode"}}, // desc
	}
	for _, tc := range cases {
		args := map[string]any{}
		if tc.sortBy != "" {
			args["sort_by"] = tc.sortBy
		}
		res := call(t, cs, "list_gcode_files", args)
		if res.IsError {
			t.Fatalf("sort_by=%q failed: %v", tc.sortBy, texts(res))
		}
		text := strings.Join(texts(res), "\n")
		last := -1
		for _, name := range tc.order {
			idx := strings.Index(text, name)
			if idx == -1 {
				t.Fatalf("sort_by=%q: missing %q in:\n%s", tc.sortBy, name, text)
			}
			if idx < last {
				t.Fatalf("sort_by=%q: %q appeared out of order:\n%s", tc.sortBy, name, text)
			}
			last = idx
		}
	}
}

