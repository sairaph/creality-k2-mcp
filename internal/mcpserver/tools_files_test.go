// buildLargeTestGCodeWithTailEstimate builds a synthetic gcode file whose
// header (thumbnail, total layer count) sits in the first few hundred
// bytes, padded well past the 1 MiB head cap with filler comment lines, and
// whose estimated-printing-time comment is appended only at the very end -
// inside the last 256 KiB tail window, but past the 1 MiB head cap - so
// get_gcode_file can only see it by actually reading the file's tail.
func buildLargeTestGCodeWithTailEstimate(thumb []byte, totalLayers int) string {
	var b strings.Builder
	b.WriteString(buildTestGCode(thumb, totalLayers))
	const filler = "; padding line to grow this synthetic file past the head cap\n"
	for b.Len() < (1<<20)+300_000 {
		b.WriteString(filler)
	}
	b.WriteString("; estimated printing time (normal mode) = 14m 33s\n")
	return b.String()
}

