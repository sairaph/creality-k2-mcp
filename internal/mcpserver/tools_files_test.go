// makeTestPNG renders a tiny solid-colour PNG for use as a synthetic
// thumbnail.
func makeTestPNG(t *testing.T, w, h int) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.Set(x, y, color.RGBA{R: 200, G: 40, B: 40, A: 255})
		}
	}
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		t.Fatalf("encode test png: %v", err)
	}
	return buf.Bytes()
}

// wrapThumbnailComment renders base64-encoded data as gcode comment lines,
// matching the real Creality Print / OrcaSlicer THUMBNAIL_BLOCK layout.
func wrapThumbnailComment(b64 string, width int) string {
	var b strings.Builder
	for len(b64) > 0 {
		n := width
		if n > len(b64) {
			n = len(b64)
		}
		b.WriteString("; ")
		b.WriteString(b64[:n])
		b.WriteString("\n")
		b64 = b64[n:]
	}
	return b.String()
}

// buildTestGCode assembles a realistic Creality Print style gcode head with
// an embedded thumbnail and a known layer count, for get_gcode_file and
// inspect_local_gcode.
func buildTestGCode(thumbData []byte, totalLayers int) string {
	b64 := base64.StdEncoding.EncodeToString(thumbData)
	var b strings.Builder
	b.WriteString("; HEADER_BLOCK_START\n")
	b.WriteString("; generated by Creality_Print V5.1.2.9904 on 2024-08-03 at 17:44:59\n")
	fmt.Fprintf(&b, "; total layer number: %d\n", totalLayers)
	b.WriteString("; HEADER_BLOCK_END\n\n")
	b.WriteString("; THUMBNAIL_BLOCK_START\n")
	b.WriteString(";\n")
	fmt.Fprintf(&b, "; thumbnail begin 32x32 %d\n", len(b64))
	b.WriteString(wrapThumbnailComment(b64, 78))
	b.WriteString("; thumbnail end\n")
	b.WriteString("; THUMBNAIL_BLOCK_END\n\n")
	b.WriteString("G28\nM104 S220\n")
	return b.String()
}

