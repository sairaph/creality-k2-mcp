// metadataHandler serves a fixed FileMetadata for every /server/files/metadata
// request, matching moonraker's own "result"-wrapped envelope for GET.
func metadataHandler(t *testing.T, md moonraker.FileMetadata) http.HandlerFunc {
	t.Helper()
	body, err := json.Marshal(map[string]any{"result": md})
	if err != nil {
		t.Fatalf("marshal metadata fixture: %v", err)
	}
	return func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		w.Write(body)
	}
}

// headRangeHandler always answers 200 with content in full, exercising the
// "server ignores Range" fallback path moonraker.Client.HeadRange already
// bounds client-side (internal/moonraker/files_test.go's own
// TestHeadRangeFallsBackWhenServerIgnoresRange covers the client half; this
// fake only needs to be simple).
func headRangeHandler(content []byte) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
		w.Write(content)
	}
}

// directoryFixtureHandler serves files/disk wrapped in the real
// server/files/directory envelope, built from typed structs (not hand-written
// JSON) so a test's expectations stay exact.
func directoryFixtureHandler(t *testing.T, files []moonraker.FileMetadata, disk moonraker.DiskUsage) http.HandlerFunc {
	t.Helper()
	type dirWire struct {
		Dirs      []moonraker.DirEntry     `json:"dirs"`
		Files     []moonraker.FileMetadata `json:"files"`
		DiskUsage moonraker.DiskUsage      `json:"disk_usage"`
		RootInfo  moonraker.RootInfo       `json:"root_info"`
	}
	body, err := json.Marshal(map[string]any{"result": dirWire{
		Files: files, DiskUsage: disk, RootInfo: moonraker.RootInfo{Name: "gcodes", Permissions: "rw"},
	}})
	if err != nil {
		t.Fatalf("marshal directory fixture: %v", err)
	}
	return func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		w.Write(body)
	}
}

// --- fakeFileStore: a small stateful gcodes-root simulation for
// upload_gcode_file/delete_gcode_file, so their settle-poll (which re-lists
// the gcodes root after sending) observes the write it just made instead of
// timing out. All loopback-only (httptest), never touches a real printer.

type fakeFileStore struct {
	mu    sync.Mutex
	files map[string]moonraker.GCodeFile
}

func newFakeFileStore(initial ...moonraker.GCodeFile) *fakeFileStore {
	s := &fakeFileStore{files: map[string]moonraker.GCodeFile{}}
	for _, f := range initial {
		s.files[f.Path] = f
	}
	return s
}

func (s *fakeFileStore) listHandler() http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		s.mu.Lock()
		list := make([]moonraker.GCodeFile, 0, len(s.files))
		for _, f := range s.files {
			list = append(list, f)
		}
		s.mu.Unlock()
		data, _ := json.Marshal(map[string]any{"result": list})
		w.Header().Set("Content-Type", "application/json")
		w.Write(data)
	}
}

func (s *fakeFileStore) uploadHandler() http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if err := r.ParseMultipartForm(10 << 20); err != nil {
			http.Error(w, err.Error(), http.StatusBadRequest)
			return
		}
		name := "uploaded.gcode"
		if fhs := r.MultipartForm.File["file"]; len(fhs) > 0 {
			name = fhs[0].Filename
		}
		s.mu.Lock()
		s.files[name] = moonraker.GCodeFile{Path: name, Size: 123, Modified: 1.0, Permissions: "rw"}
		s.mu.Unlock()
		w.Header().Set("Content-Type", "application/json")
		fmt.Fprintf(w, `{"item": {"root": "gcodes", "path": %q, "modified": 1.0, "size": 123, "permissions": "rw"}, "print_started": false, "print_queued": false, "action": "create_file"}`, name)
	}
}

// gcodesPathHandler serves DELETE for /server/files/gcodes/<name> against
// the same in-memory store; a GET here is never exercised by the
// upload/delete tests (only by get_gcode_file, which serves its own
// headRangeHandler override instead).
func (s *fakeFileStore) gcodesPathHandler() http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodDelete {
			w.WriteHeader(http.StatusOK)
			return
		}
		name := strings.TrimPrefix(r.URL.Path, "/server/files/gcodes/")
		name, _ = url.PathUnescape(name)
		s.mu.Lock()
		_, existed := s.files[name]
		delete(s.files, name)
		s.mu.Unlock()
		if !existed {
			w.WriteHeader(http.StatusBadRequest)
			fmt.Fprintf(w, `{"error": {"code": 400, "message": "Invalid file path: gcodes/%s"}}`, name)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		fmt.Fprintf(w, `{"result": {"item": {"root": "gcodes", "path": %q}, "action": "delete_file"}}`, name)
	}
}

