// extractYAMLField pulls "key: value" from text's first matching line (the
// frontmatter block), trimming any surrounding quotes YAML may have added.
func extractYAMLField(t *testing.T, text, key string) string {
	t.Helper()
	prefix := key + ": "
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, prefix) {
			return strings.Trim(strings.TrimPrefix(line, prefix), `"`)
		}
	}
	t.Fatalf("field %q not found in:\n%s", key, text)
	return ""
}
